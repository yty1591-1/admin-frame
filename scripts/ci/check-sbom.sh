#!/usr/bin/env bash
# ENT-19 / RELEASE_STANDARDS §6：供应链门禁。
#
# 只做静态断言（无网络、无镜像、无 cosign 也能跑），校验的是「流水线结构是否正确」：
#   SB-01 keyless 前提：image.yml 必须声明 id-token: write
#   SB-02 SBOM 按 digest 生成，格式为 CycloneDX
#   SB-03 SBOM 作为 artifact 上传（人可下载），缺文件必须失败
#   SB-04 签名对象是 digest（不是 tag），且发生在构建之后
#   SB-05 SBOM 以 attestation 形式附加到同一 digest
#   SB-06 供应链工具版本钉扎（禁 latest / master / 浮动大版本）
#   SB-07 发布流水线调用 verify-supply-chain.sh，且先于第一次 helm upgrade
#   SB-08 verify 必须是 staging 的依赖（不放进 needs 就能被绕过）
#   SB-09 验签脚本本身不得留后门（拒绝 tag 引用、拒绝通配身份、固定 issuer、校验 SBOM 内容）
#   SB-10 禁止绕过：无 continue-on-error / 无 --insecure-ignore-tlog / 无 || true
#   SB-11 文档与 Checklist 已回写（RELS-13 / RELS-14）
#
# 匹配一律剔除注释行：本文件的说明性注释同样出现在 workflow 里，
# 「注释里有 cosign sign」不能算作「流水线真的签了名」。
#
# 用法: bash scripts/ci/check-sbom.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "${ROOT}"

FAIL=0
IMG_WF=".github/workflows/image.yml"
REL_WF=".github/workflows/release.yml"
VERIFY="scripts/ci/verify-supply-chain.sh"

err() {
  echo "ERROR: $*" >&2
  FAIL=1
}
ok() { echo "    OK: $*"; }

# code_has <file> <ere>：只在非注释行里匹配（workflow 文件头注释常引用关键字）
code_has() {
  # `--` 必需：模式可能以 '--predicate' 这类选项形态开头，否则 grep 会把它当参数解析。
  grep -vE '^[[:space:]]*#' "$1" 2>/dev/null | grep -qE -- "$2"
}

# code_line <file> <ere>：返回命中行号（跳过注释行），无命中返回空
code_line() {
  grep -nE -- "$2" "$1" 2>/dev/null |
    awk -F: '{ln=$1; sub(/^[0-9]+:/,""); if ($0 !~ /^[[:space:]]*#/) {print ln; exit}}'
}

# step_block <file> <step 名前缀>：取一个 step 块（到下一个同级 step 为止）
step_block() {
  awk -v want="$2" '
    !f && $0 ~ ("- name: " want) {f=1; print; next}
    f && /^[[:space:]]*- name:/ {exit}
    f {print}
  ' "$1"
}

# job_needs <file> <job>：取某个 job 的 needs 行内容
job_needs() {
  awk -v job="$2" '
    $0 ~ "^  " job ":$" {f=1; next}
    f && /^  [A-Za-z0-9_-]+:$/ {exit}
    f && /^[[:space:]]+needs:/ {sub(/^[[:space:]]+needs:[[:space:]]*/,""); print; exit}
  ' "$1"
}

for f in "${IMG_WF}" "${REL_WF}" "${VERIFY}"; do
  if [[ ! -f "${f}" ]]; then
    echo "ERROR: missing ${f}（ENT-19 供应链）" >&2
    exit 1
  fi
done

echo "==> SB-01: keyless signing prerequisite (id-token: write)"
if grep -qE '^[[:space:]]+id-token:[[:space:]]*write' "${IMG_WF}"; then
  ok 'id-token: write'
else
  err "${IMG_WF} 缺少 'id-token: write'：没有 OIDC 令牌就取不到 Fulcio 证书，cosign 只能签出空/失败（SB-01）"
fi

echo "==> SB-02: SBOM generated by digest (CycloneDX)"
if code_has "${IMG_WF}" 'format:[[:space:]]*cyclonedx'; then
  ok "format: cyclonedx"
else
  err "${IMG_WF} 未生成 CycloneDX SBOM（SB-02）"
fi
sbom_step="$(step_block "${IMG_WF}" 'SBOM')"
if [[ -z "${sbom_step}" ]]; then
  err "无法定位 ${IMG_WF} 中的 SBOM step（SB-02）"
elif printf '%s' "${sbom_step}" | grep -q 'steps\.build\.outputs\.digest'; then
  ok "SBOM step 按 steps.build.outputs.digest"
else
  err "SBOM step 未按构建产出的 digest 生成——按 tag 生成会与最终部署的 digest 脱钩（SB-02）"
fi

echo "==> SB-03: SBOM uploaded as artifact (fail on missing)"
if code_has "${IMG_WF}" 'actions/upload-artifact@'; then
  ok "upload-artifact wired"
else
  err "${IMG_WF} 未上传 SBOM artifact（供应链评审需要可直接下载的 SBOM，SB-03）"
fi
if code_has "${IMG_WF}" 'if-no-files-found:[[:space:]]*error'; then
  ok "if-no-files-found: error"
else
  err "${IMG_WF} 上传 SBOM 缺 'if-no-files-found: error'：SBOM 生成失败会被静默跳过（SB-03）"
fi

echo "==> SB-04: image signature targets digest, after build"
sign_line="$(code_line "${IMG_WF}" 'cosign sign')"
build_line="$(code_line "${IMG_WF}" 'uses: docker/build-push-action@')"
if [[ -z "${sign_line}" ]]; then
  err "${IMG_WF} 未签名镜像（SB-04）"
else
  if code_has "${IMG_WF}" 'cosign sign.*DIGEST'; then
    ok "cosign sign 使用 digest"
  else
    err "${IMG_WF} 的 cosign sign 未使用 digest 变量：签 tag 等于没签（SB-04）"
  fi
  if [[ -n "${build_line}" && "${sign_line}" -lt "${build_line}" ]]; then
    err "cosign sign 出现在构建之前（第 ${sign_line} 行 < 第 ${build_line} 行），签不到任何产物（SB-04）"
  else
    ok "sign 在 build 之后"
  fi
fi

echo "==> SB-05: SBOM attested onto the same digest"
if code_has "${IMG_WF}" 'cosign attest'; then
  ok "cosign attest wired"
  if code_has "${IMG_WF}" 'attest.*--type cyclonedx'; then
    ok "--type cyclonedx"
  else
    err "${IMG_WF} 的 cosign attest 未声明 --type cyclonedx（发布侧按该类型取回 SBOM，SB-05）"
  fi
  if code_has "${IMG_WF}" '--predicate'; then
    ok "--predicate supplied"
  else
    err "${IMG_WF} 的 cosign attest 缺 --predicate：没有 SBOM 内容的 attestation 毫无意义（SB-05）"
  fi
else
  err "${IMG_WF} 未把 SBOM 作为 attestation 附加到 digest（SB-05）"
fi

echo "==> SB-06: supply chain tool versions pinned"
if code_has "${IMG_WF}" 'sigstore/cosign-installer@'; then
  ok "cosign-installer pinned"
else
  err "${IMG_WF} 未使用 sigstore/cosign-installer（SB-06）"
fi
if code_has "${IMG_WF}" 'cosign-release:[[:space:]]*\$\{\{|cosign-release:[[:space:]]*v[0-9]'; then
  ok "cosign-release pinned"
else
  err "${IMG_WF} 的 cosign 版本未钉扎到具体 release（SB-06）"
fi
for pat in '@latest' '@master' '@main'; do
  if code_has "${IMG_WF}" "uses:.*${pat}"; then
    err "${IMG_WF} 存在浮动引用的 action（${pat}），供应链工具必须钉版本（SB-06）"
  fi
done
if code_has "${IMG_WF}" 'uses: aquasecurity/trivy-action@v?[0-9]+\.[0-9]+\.[0-9]+'; then
  ok "trivy-action pinned to x.y.z"
else
  err "${IMG_WF} 的 trivy-action 未钉到 x.y.z（SB-06）"
fi

echo "==> SB-07: release verifies before the first helm upgrade"
verify_line="$(code_line "${REL_WF}" 'verify-supply-chain\.sh')"
upgrade_line="$(code_line "${REL_WF}" 'helm upgrade')"
if [[ -z "${verify_line}" ]]; then
  err "${REL_WF} 未调用 ${VERIFY}：未验签就部署（RELS-14）"
elif [[ -n "${upgrade_line}" && "${verify_line}" -gt "${upgrade_line}" ]]; then
  err "验签必须早于第一次 helm upgrade（第 ${verify_line} 行 > 第 ${upgrade_line} 行）（SB-07）"
else
  ok "verify 先于首次升级"
fi

echo "==> SB-08: verify job is a hard dependency of staging"
needs="$(job_needs "${REL_WF}" staging)"
if [[ -z "${needs}" ]]; then
  err "无法解析 ${REL_WF} 中 staging job 的 needs（SB-08）"
elif printf '%s' "${needs}" | tr -d '[]' | tr ',' '\n' | tr -d ' \t' | grep -qx 'verify'; then
  ok "staging needs verify（${needs}）"
else
  err "staging 的 needs 不含 verify（当前 '${needs}'）：验签会变成可跳过步骤（SB-08）"
fi

echo "==> SB-09: verification script has no bypass"
# 行为断言：真跑脚本，要求它在调用 cosign 之前就以**指定理由**拒绝。
# 用 COSIGN_BIN=/bin/false 保证「即使护栏被删，脚本也会因为签名失败而退出」，
# 因此必须匹配具体错误文案，否则「删除护栏」会被误判为通过。
# 注意：不能写成 `cmd 2>&1 | grep -q`——`set -o pipefail` 下 grep 命中后提前退出会让左侧收到
# SIGPIPE（141），整个 pipeline 反而非 0，护栏被删也能「报错」，形成假通过。
DUMMY_REF="example.com/admin-frame/admin-api@sha256:$(printf 'a%.0s' $(seq 1 64))"
# $1=cosign identity（空=用脚本默认） $2=issuer（空=默认） 其余=镜像参数
verify_out() {
  local id="$1" issuer="$2"; shift 2
  env GITHUB_REPOSITORY=acme/admin-frame COSIGN_BIN=/bin/false \
    COSIGN_IDENTITY_REGEXP="${id}" COSIGN_OIDC_ISSUER="${issuer}" \
    bash "${VERIFY}" "$@" 2>&1 || true
}
out="$(verify_out "" "" 'example.com/admin-frame/admin-api:1.2.3')"
if grep -q '必须是 <image>@sha256' <<<"${out}"; then
  ok "拒绝按 tag 验签"
else
  err "${VERIFY} 未在验签前拒绝 tag 引用：按 tag 验签可被 TOCTOU 绕过（SB-09）"
fi
out="$(verify_out '.*' "" "${DUMMY_REF}")"
if grep -q '过于宽松' <<<"${out}"; then
  ok "拒绝纯通配身份"
else
  err "${VERIFY} 未拒绝纯通配身份（'.*' 等于不校验来源，SB-09）"
fi
# 形态合法但含 `.*` 的身份（例如把 owner 换成通配）——两道护栏里的第二道专门管这个，
# 只测纯 '*' 会因为第一道护栏先命中而测不出第二道是否存在。
out="$(verify_out '^https://github\.com/.*/\.github/workflows/image\.yml@refs/(heads|tags)/' "" "${DUMMY_REF}")"
if grep -q "含 '\.\*'" <<<"${out}"; then
  ok "拒绝含 .* 的通配身份"
else
  err "${VERIFY} 未拒绝含 '.*' 的身份：把 owner 换成通配即可冒充任意仓库（SB-09）"
fi
out="$(verify_out "" "http://evil.example" "${DUMMY_REF}")"
if grep -q '必须是 https issuer' <<<"${out}"; then
  ok "拒绝非 https issuer"
else
  err "${VERIFY} 未约束 OIDC issuer：换 issuer 可自签证书冒充（SB-09）"
fi
if grep -q 'token.actions.githubusercontent.com' "${VERIFY}"; then
  ok "OIDC issuer 固定为 GitHub Actions"
else
  err "${VERIFY} 未固定 OIDC issuer（换 issuer 可自签证书冒充，SB-09）"
fi
if grep -q 'verify-attestation' "${VERIFY}"; then
  ok "校验 SBOM attestation"
else
  err "${VERIFY} 只验签名不验 attestation：无法确认镜像带 SBOM（SB-09）"
fi
if grep -q 'bomFormat' "${VERIFY}"; then
  ok "校验 SBOM 载荷内容"
else
  err "${VERIFY} 未校验 attestation 载荷内容：空 SBOM 也能通过（SB-09）"
fi

echo "==> SB-10: no bypass in the release pipeline"
for pat in 'continue-on-error:[[:space:]]*true' '--insecure-ignore-tlog' '--certificate-identity-regexp[[:space:]]+\.\*'; do
  if code_has "${REL_WF}" "${pat}"; then
    err "${REL_WF} 出现绕过验签的配置：${pat}（SB-10）"
  fi
done
if code_has "${REL_WF}" 'verify-supply-chain\.sh.*\|\|[[:space:]]*true'; then
  err "${REL_WF} 对 ${VERIFY} 使用了 '|| true'：验签失败被吞掉（SB-10）"
else
  ok "无 || true / continue-on-error / ignore-tlog"
fi

echo "==> SB-11: standards + checklist updated"
if grep -qE '^\| RELS-13' docs/RELEASE_STANDARDS.md && grep -qE '^\| RELS-14' docs/RELEASE_STANDARDS.md; then
  ok "RELS-13 / RELS-14 present"
else
  err "docs/RELEASE_STANDARDS.md 缺 RELS-13/RELS-14（SB-11）"
fi
if grep -qiE 'SBOM' docs/RELEASE_STANDARDS.md && grep -qiE 'cosign' docs/RELEASE_STANDARDS.md; then
  ok "§6 mentions SBOM + cosign"
else
  err "docs/RELEASE_STANDARDS.md §6 未描述 SBOM / 签名要求（SB-11）"
fi
if grep -qiE 'SBOM|验签|签名' docs/release/CHECKLIST.md; then
  ok "release checklist covers supply chain"
else
  err "docs/release/CHECKLIST.md 未把 SBOM / 验签列入发版自检（SB-11）"
fi

if [[ "${FAIL}" -ne 0 ]]; then
  echo "supply chain check failed (ENT-19 / RELEASE_STANDARDS §6)" >&2
  exit 1
fi
echo "OK: sbom"
