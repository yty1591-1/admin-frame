const fs = require('fs');
const f = 'internal/iam/transport/admin/handler_test.go';
let s = fs.readFileSync(f, 'utf8');
const oldImport = '\t"github.com/admin-frame/admin-frame/internal/iam/transport/admin"';
if (!s.includes(oldImport)) throw new Error('import not found');
s = s.replace(oldImport, oldImport + '\n\t"github.com/admin-frame/admin-frame/internal/iam/transport/rest"');
s = s.split('admin.NewHandler(').join('rest.NewHandler(');
s = s.split('admin.HandlerConfig').join('rest.HandlerConfig');
fs.writeFileSync(f, s);
console.log('updated', s.includes('rest.NewHandler'));
