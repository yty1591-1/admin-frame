-- 清理历史设备会话中由回环 / 未指定地址派生的无效脱敏 IP。
--
-- 背景：
--   早期 MaskIP 未过滤 127.0.0.1 / ::1，落库得到 127.0.x.x、0.0.x.x 或
--   0:0:0:0:x:x:x:x；这些值对用户没有设备区分意义，前端无法合理解释。
-- 变更：
--   仅清空上述无效值；真实公网 / 内网 IP 的脱敏结果保持不变。
-- 回滚：
--   无法还原原始脱敏值（且这些值本就无意义），阅读路径已兜底清空，无需回滚。

UPDATE identity_session_family
SET ip_masked = ''
WHERE ip_masked IN ('0.0.x.x', '127.0.x.x')
   OR ip_masked LIKE '0:0:0:0:%';
