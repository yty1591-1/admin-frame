#!/usr/bin/env node
/**
 * 契约类型生成（FE-08 / GEN-01）。
 * 源：api/openapi/{admin,biz}.yaml；输出入库且带生成头，禁止手改。
 * CI 重新生成后执行 git diff --exit-code 校验无漂移。
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const frontendRoot = fileURLToPath(new URL('..', import.meta.url));
const repoRoot = path.resolve(frontendRoot, '..');

const targets = [
  { channel: 'admin', source: path.join(repoRoot, 'api/openapi/admin.yaml') },
  { channel: 'biz', source: path.join(repoRoot, 'api/openapi/biz.yaml') },
];

function header(channel) {
  return `// Code generated by openapi-typescript 7.4.0 from api/openapi/${channel}.yaml. DO NOT EDIT.\n\n`;
}

for (const target of targets) {
  const ast = await openapiTS(pathToFileURL(target.source));
  const contents = astToString(ast).replace(/\r\n/g, '\n');
  const output = path.join(
    frontendRoot,
    'packages/api-client/src/generated',
    `${target.channel}.ts`,
  );
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, `${header(target.channel)}${contents}`, 'utf8');
  console.log(`generated ${path.relative(frontendRoot, output)}`);
}
